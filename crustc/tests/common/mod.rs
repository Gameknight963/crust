use std::fs;
use std::path::PathBuf;
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};
pub mod compiler;
mod files;

static NEXT_CASE: AtomicUsize = AtomicUsize::new(0);

#[allow(dead_code)]
pub fn tracked_file_source() -> String {
    return files::native_source();
}

#[allow(dead_code)]
pub fn allocation_source() -> String {
    return include_str!("../../../lib/allocation.cr").replace(
        "import \"result.cr\";",
        include_str!("../../../lib/result.cr"),
    );
}

#[allow(dead_code)]
pub fn assert_example(relative: &str, stdout: &str, stderr: &str, sizes: bool) {
    let path = PathBuf::from(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap(),
    )
    .join(relative);
    let generated = crustc::source::SourceSet::load(&path)
        .unwrap()
        .compile()
        .unwrap();
    let output = tracked_generated_c(&generated, sizes);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert_eq!(
        String::from_utf8_lossy(&output.stdout).replace('\r', ""),
        stdout
    );
    assert_eq!(
        String::from_utf8_lossy(&output.stderr).replace('\r', ""),
        stderr
    );
}

// Instrument the generated C's allocator, rather than inferring cleanup from
// text matching. Real compiled executions verify frees and their scope order.
#[allow(dead_code)]
pub fn tracked_run(source: &str) -> Output {
    return run_with_tracking(source, false);
}

// Each integration test compiles this module independently.
#[allow(dead_code)]
pub fn tracked_run_sizes(source: &str) -> Output {
    return run_with_tracking(source, true);
}

fn run_with_tracking(source: &str, sizes: bool) -> Output {
    let source = compiler::fixture(source);
    let generated = if source
        .lines()
        .any(|line| line.trim_start().starts_with('#'))
    {
        let prefix = tracking_prefix(sizes).replace("#define main crust_test_main", "");
        let source = format!(
            "#pragma crust begin_c\n{prefix}\nstatic int crust_test_finish(int result) {{if(live_allocations) {{fprintf(stderr,\"leaked %zu allocation(s)\\n\",live_allocations);return 99;}}return result;}}\n#pragma crust end_c\n#define main crust_test_main\n{source}\n#undef main\nint main() {{\n#ifdef CRUST_TEST_ALLOCATION_BUDGET\ncrust_test_fail_allocations_after(CRUST_TEST_ALLOCATION_BUDGET);\n#endif\nint result=crust_test_main();return crust_test_finish(result);}}\n"
        );
        ::crustc::compile(&source).unwrap()
    } else {
        compiler::compile(&source).unwrap()
    };
    return tracked_generated_c(&generated, sizes);
}

#[allow(dead_code)]
pub fn tracked_generated_c(generated: &str, sizes: bool) -> Output {
    return tracked_generated_c_arguments(generated, sizes, None);
}

#[allow(dead_code)]
pub fn tracked_generated_c_with_args(generated: &str, sizes: bool, arguments: &[String]) -> Output {
    return tracked_generated_c_arguments(generated, sizes, Some(arguments));
}

fn tracked_generated_c_arguments(
    generated: &str,
    sizes: bool,
    arguments: Option<&[String]>,
) -> Output {
    let directory = PathBuf::from(
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap(),
    )
    .join("target")
    .join("ownership-tests");
    fs::create_dir_all(&directory).unwrap();
    let id = NEXT_CASE.fetch_add(1, Ordering::Relaxed);
    let path = directory.join(format!("case_{}_{}.c", std::process::id(), id));
    let executable = path.with_extension(std::env::consts::EXE_EXTENSION);
    let prefix = tracking_prefix(sizes);
    let suffix = r#"
        #undef main
        #undef malloc
        #undef free
        int main(void) {
            #ifdef CRUST_TEST_ALLOCATION_BUDGET
            crust_test_fail_allocations_after(CRUST_TEST_ALLOCATION_BUDGET);
            #endif
            int result = crust_test_main();
            if (live_allocations != 0) {
                fprintf(stderr, "leaked %zu allocation(s)\n", live_allocations);
                return 99;
            }
            return result;
        }
    "#;
    let suffix = if arguments.is_some() {
        suffix
            .replace("int main(void)", "int main(int argc, char** argv)")
            .replace("crust_test_main()", "crust_test_main(argc, argv)")
    } else {
        suffix.to_owned()
    };
    // Native imports shield their symbols from header macros before the runtime.
    // Restore allocator hooks there so runtime allocation helpers stay tracked.
    let generated = generated.replace(
        "/* Generated by Crust. */",
        "#define malloc tracked_malloc\n#define free tracked_free\n/* Generated by Crust. */",
    );
    let preprocessed = generated.starts_with("/* Crust preprocessed C.");
    fs::write(
        &path,
        if preprocessed {
            generated.clone()
        } else {
            format!("{prefix}\n{generated}\n{suffix}")
        },
    )
    .unwrap();
    let sanitizers = match std::env::var("CRUST_TEST_SANITIZERS").as_deref() {
        Ok("address") => vec![crustc::native::Sanitizer::Address],
        Ok("undefined") => vec![crustc::native::Sanitizer::Undefined],
        Ok("address,undefined") => vec![
            crustc::native::Sanitizer::Address,
            crustc::native::Sanitizer::Undefined,
        ],
        Ok("") | Err(_) => Vec::new(),
        Ok(value) => panic!("unsupported CRUST_TEST_SANITIZERS value: {value}"),
    };
    let options = crustc::native::Options {
        sanitizers,
        ..Default::default()
    };
    crustc::native::compile_file_with_options(&path, &executable, &options).unwrap();
    return Command::new(executable)
        .current_dir(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .unwrap(),
        )
        .args(arguments.unwrap_or(&[]))
        .output()
        .unwrap();
}

fn tracking_prefix(sizes: bool) -> String {
    return r#"
        #include <stdlib.h>
        #include <stdio.h>
        #include <stdint.h>
        #include <inttypes.h>
        #include <string.h>
        struct tracked_allocation { void *pointer; size_t size; struct tracked_allocation *next; };
        static struct tracked_allocation *allocations = NULL;
        static size_t live_allocations = 0;
        static size_t allocation_budget = SIZE_MAX;
        static void crust_test_fail_allocations_after(size_t successes) {
            allocation_budget = successes;
        }
        static void *tracked_malloc(size_t bytes) {
            if (allocation_budget == 0) { return NULL; }
            if (allocation_budget != SIZE_MAX) { allocation_budget -= 1; }
            void *value = malloc(bytes);
            if (value != NULL) {
                struct tracked_allocation *record = malloc(sizeof(*record));
                if (record == NULL) { free(value); return NULL; }
                record->pointer = value; record->size = bytes; record->next = allocations;
                allocations = record;
                live_allocations += 1;
            }
            return value;
        }
        static void tracked_free(void *value) {
            if (value != NULL) {
                struct tracked_allocation **link = &allocations;
                while (*link != NULL && (*link)->pointer != value) { link = &(*link)->next; }
                if (*link == NULL) { fprintf(stderr, "invalid free\n"); exit(98); }
                struct tracked_allocation *record = *link;
                *link = record->next;
                if (CRUST_TEST_LOG_SIZES || record->size < sizeof(int32_t)) {
                    fprintf(stderr, "drop:bytes:%zu\n", record->size);
                } else {
                    int32_t contents;
                    memcpy(&contents, value, sizeof(contents));
                    fprintf(stderr, "drop:%" PRId32 "\n", contents);
                }
                free(record);
                live_allocations -= 1;
            }
            free(value);
        }
        #define malloc tracked_malloc
        #define free tracked_free
        #define main crust_test_main
    "#
    .replace("CRUST_TEST_LOG_SIZES", if sizes { "1" } else { "0" });
}

#[allow(dead_code)]
pub fn native_header(path: &std::path::Path) -> String {
    return format!(
        "#pragma crust begin_c\n#include {}\n#pragma crust end_c\n",
        serde_json::to_string(&path.to_string_lossy().replace('\\', "/")).unwrap()
    );
}

#[allow(dead_code)]
pub fn tracked_with_native(source: &str, native: &str) -> Output {
    return tracked_run(&format!(
        "{source}\n#pragma crust begin_c\n{native}\n#pragma crust end_c\n"
    ));
}

#[allow(dead_code)]
pub fn tracked_file(path: &std::path::Path, native: &str, sizes: bool) -> Output {
    let path = path.canonicalize().unwrap();
    let prefix = tracking_prefix(sizes).replace("#define main crust_test_main", "");
    let original = std::fs::read_to_string(&path).unwrap();
    let text = format!(
        "#pragma crust begin_c\n{prefix}\nstatic int crust_test_finish(int result){{if(live_allocations){{fprintf(stderr,\"leaked %zu allocation(s)\\n\",live_allocations);return 99;}}return result;}}\n#pragma crust end_c\n#define main crust_test_main\n{original}\n#pragma crust begin_c\n{native}\n#pragma crust end_c\n#undef main\nint main(){{int result=crust_test_main();return crust_test_finish(result);}}\n"
    );
    let sources = ::crustc::source::SourceSet::load_with(&path, |input| {
        if input == path {
            Ok(text.clone())
        } else {
            std::fs::read_to_string(input)
        }
    })
    .unwrap();
    return tracked_generated_c(&sources.compile().unwrap(), sizes);
}
